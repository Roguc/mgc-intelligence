def assert_state(state: str) -> str:
    if state not in ALL_STATES:
        raise ValueError(f"Estado corporativo no válido: {state}")
    return state


def assert_transition(current: str, new: str) -> None:
    assert_state(current)
    assert_state(new)
    if new not in TRANSITIONS.get(current, frozenset()):
        raise ValueError(f"Transición no permitida: {current} → {new}")
